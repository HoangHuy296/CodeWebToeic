#!/usr/bin/env node
// Generates the Flyway seed for the TOEIC Winner "ETS 2026 - Part 5" sentence bank from the
// ets2026-testNN_items.json exports. Re-run it after editing the JSON, then review the diff.
//
//   node scripts/generate-winner-ets-migration.mjs [sourceDir] [outFile]
//
// Each file becomes one chapter ("ETS 2026 · Test NN") of the TOEIC Winner course; the JSON
// `alts` become the `|`-separated other_answers the grader accepts.
import fs from 'node:fs';
import path from 'node:path';

const sourceDir = process.argv[2] ?? 'TOEIC WINNER E26 P5';
const outFile = process.argv[3] ?? 'backend-spring/src/main/resources/db/migration/mysql/V16__seed_winner_ets2026_part5.sql';

const COURSE = { slug: 'toeic-winner', name: 'TOEIC Winner', order: 3 };
const sql = (value) => (value == null ? 'NULL' : `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "''")}'`);
const fail = (message) => {
  console.error(`ERROR: ${message}`);
  process.exit(1);
};

const files = fs
  .readdirSync(sourceDir)
  .filter((name) => /^ets2026-test\d+_items\.json$/.test(name))
  .sort();
if (files.length === 0) fail(`no ets2026-testNN_items.json files in ${sourceDir}`);

// "Web site" is ETS house style; learners very often type "website".
const withSpellingVariants = (en, alts) => {
  const variants = new Set(alts);
  if (/\bWeb site\b/.test(en)) variants.add(en.replace(/\bWeb site\b/g, 'Website'));
  return [...variants];
};

const rows = [];
files.forEach((file, fileIndex) => {
  const testNo = Number(/test(\d+)/.exec(file)[1]);
  const label = String(testNo).padStart(2, '0');
  const items = JSON.parse(fs.readFileSync(path.join(sourceDir, file), 'utf8'));
  if (!Array.isArray(items) || items.length === 0) fail(`${file}: expected a non-empty array`);

  items.forEach((item, index) => {
    const where = `${file} #${index + 1}`;
    for (const key of ['en', 'vi', 'part', 'topic']) {
      if (typeof item[key] !== 'string' || !item[key].trim()) fail(`${where}: missing ${key}`);
    }
    const alts = withSpellingVariants(item.en, item.alts ?? []);
    if ([item.en, ...alts].some((text) => text.includes('|'))) fail(`${where}: "|" is the answer separator`);
    if (item.en.length > 500 || item.vi.length > 500) fail(`${where}: longer than 500 characters`);

    const questionNo = /^Câu (\d+)/u.exec(item.note ?? '')?.[1] ?? String(index + 1);
    rows.push(
      `(${[
        sql(`wn26-${label}-${questionNo}`),
        sql(`ETS 2026 · Test ${label}`),
        sql(`winner-e26-p5-${label}`),
        sql(item.en),
        sql(item.vi),
        sql(item.part),
        sql(item.topic),
        sql(item.note ?? null),
        sql(alts.length ? alts.join('|') : null),
        'NULL',
        'NULL',
        index + 1,
        sql(COURSE.slug),
        sql(COURSE.name),
        COURSE.order,
        fileIndex + 1,
        'UTC_TIMESTAMP()',
        'UTC_TIMESTAMP()',
      ].join(', ')})`,
    );
  });
});

const header = `-- TOEIC Winner course: "ETS 2026 - Part 5" sentence bank (${files.length} tests x 30 questions).
-- Generated by scripts/generate-winner-ets-migration.mjs from the ets2026-testNN_items.json
-- exports — edit the JSON and re-run the script instead of editing this file by hand.

DELETE FROM word_items WHERE course_slug = 'toeic-winner' AND set_slug LIKE 'winner-e26-p5-%';

INSERT INTO word_items (id, set_name, set_slug, en, vi, part, topic, note, other_answers, example_en, example_vi, sort_order, course_slug, course_name, course_order, set_order, created_at, updated_at) VALUES
`;

fs.writeFileSync(outFile, `${header}${rows.join(',\n')};\n`, 'utf8');
console.log(`Wrote ${rows.length} items from ${files.length} files to ${outFile}`);
